/// A date in Bikram Sambat (BS), the official calendar of Nepal.
///
/// BS months don't follow a formula — their lengths are set each year from the
/// astronomical almanac — so conversion uses a published table of month lengths.
/// Table: BS 2000–2090 (14 Apr 1943 – mid-April 2034), from the
/// `nepali-date-converter` npm package (v3.4.2). Checked against known new-year
/// days: 2080 → 14 Apr 2023, 2081 → 13 Apr 2024, 2082 → 14 Apr 2025.
struct NepaliDate: Equatable {
    let year: Int
    let month: Int   // 1 = Baisakh … 12 = Chaitra
    let day: Int
    let weekday: Int // 1 = Sunday … 7 = Saturday

    /// The BS date of the local calendar day that contains `date`, or nil outside the table.
    init?(_ date: Date, calendar: Calendar = .current) {
        var gregorian = Calendar(identifier: .gregorian)
        gregorian.timeZone = calendar.timeZone
        let parts = calendar.dateComponents([.year, .month, .day], from: date)
        guard let today = gregorian.date(from: parts),
              let epoch = gregorian.date(from: DateComponents(year: 1943, month: 4, day: 14)),
              var remaining = gregorian.dateComponents([.day], from: epoch, to: today).day,
              remaining >= 0 else { return nil }

        weekday = gregorian.component(.weekday, from: today)
        for (index, months) in Self.monthLengths.enumerated() {
            let yearLength = months.reduce(0, +)
            if remaining >= yearLength { remaining -= yearLength; continue }
            for (m, length) in months.enumerated() {
                if remaining < length {
                    year = Self.firstYear + index
                    month = m + 1
                    day = remaining + 1
                    return
                }
                remaining -= length
            }
        }
        return nil
    }

    static let monthNames = ["बैशाख", "जेठ", "असार", "साउन", "भदौ", "असोज",
                             "कात्तिक", "मंसिर", "पुस", "माघ", "फागुन", "चैत"]
    static let monthNamesLatin = ["Baisakh", "Jestha", "Asar", "Shrawan", "Bhadra", "Ashwin",
                                  "Kartik", "Mangsir", "Poush", "Magh", "Falgun", "Chaitra"]
    static let weekdayNames = ["आइतबार", "सोमबार", "मंगलबार", "बुधबार", "बिहीबार", "शुक्रबार", "शनिबार"]

    /// e.g. "मंसिर ७, २०८३"
    var formatted: String { "\(Self.monthNames[month - 1]) \(Self.devanagari(day)), \(Self.devanagari(year))" }
    /// e.g. "Mangsir 7, 2083"
    var formattedLatin: String { "\(Self.monthNamesLatin[month - 1]) \(day), \(year)" }
    /// e.g. "आइतबार"
    var weekdayName: String { Self.weekdayNames[weekday - 1] }

    static func devanagari(_ n: Int) -> String {
        String(String(n).map { c in
            c.wholeNumberValue.map { Character(Unicode.Scalar(0x0966 + $0)!) } ?? c
        })
    }

